"""Pin downloadable data resources. No APK, DEX or native code is downloaded."""
import gzip, hashlib, json, pathlib, shutil
ROOT = pathlib.Path(__file__).resolve().parents[1]
PAYLOAD = ROOT / 'components' / 'payloads'
CATALOG = ROOT / 'components' / 'catalogue.json'

def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()

def main():
    PAYLOAD.mkdir(parents=True, exist_ok=True)
    dictionary = PAYLOAD / 'ecdict-v1.db.gz'
    h = hashlib.sha256(); size = 0
    with gzip.open(dictionary, 'rb') as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b''):
            h.update(chunk); size += len(chunk)
    records = {'dictionary': dict(id='dictionary-v1', fileName=dictionary.name,
        bytes=dictionary.stat().st_size, sha256=digest(dictionary), unpackedBytes=size, unpackedSha256=h.hexdigest())}
    source = ROOT / 'vendor/open-android-doc-scanner-0.7.0/scanner-processing-opencv/src/main/assets/docquad/docquadnet256.ort'
    sha = digest(source)
    if source.stat().st_size != 13404960 or sha != 'f0f2f52d7d79ff02d346c8f9d0c9e903407366aeea1747cdcff160c401e3e72a':
        raise RuntimeError('Unexpected scanner model; review the runtime pin before publishing')
    name = f'docquadnet256-{sha[:16]}.ort'
    target = PAYLOAD / name
    if target.exists() and digest(target) != sha:
        raise RuntimeError('Refusing to overwrite immutable model data')
    if not target.exists():
        shutil.copy2(source, target)
    records['scanner-model'] = dict(id='scanner-model-v1',fileName=name,bytes=source.stat().st_size,
        sha256=sha,unpackedBytes=source.stat().st_size,unpackedSha256=sha)
    CATALOG.write_text(json.dumps(records, indent=2) + '\n', 'utf-8')
    def kotlin(record):
        values = [json.dumps(record[k]) for k in ('id', 'fileName')]
        values += [json.dumps('https://39.105.161.86/components/' + record['fileName'])]
        values += [str(record['bytes'])+'L',json.dumps(record['sha256']),str(record['unpackedBytes'])+'L',json.dumps(record['unpackedSha256'])]
        return 'ComponentSpec(' + ','.join(values) + ')'
    out = ['package cn.dapan.assistant', '', '// Generated by scripts/component-catalogue.py; data hashes are pinned in the app.',
        'internal object ComponentCatalog {', ' val dictionary = '+kotlin(records['dictionary']),
        ' val scannerModel = '+kotlin(records['scanner-model']), '}', '']
    (ROOT / 'app/src/main/java/cn/dapan/assistant/ComponentCatalog.kt').write_text('\n'.join(out),'utf-8')
    print(json.dumps({k:dict(bytes=v['bytes'],sha256=v['sha256']) for k,v in records.items()}))

if __name__ == '__main__':
    main()
