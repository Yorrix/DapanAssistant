"""Regenerate/check the cross-page operation catalogue from actual adapters."""
from pathlib import Path
import json,re,sys
root=Path(__file__).resolve().parents[1]
source=root/'app/src/main/java/cn/dapan/assistant'
modules={"今天":["TodayDashboard.kt"],"日历":["CalendarUi.kt"],"账单":["BillingUi.kt"],"信息查询":["InformationScreen.kt"],"晨签":["MorningUi.kt"],"天气":["WeatherUi.kt"],"手持弹幕":["MarqueeUi.kt"],"工具":["ToolboxUi.kt"],"专注":["FocusUi.kt"],"抽签":["WheelUi.kt"],"官网通知":["NoticeScreen.kt"],"实时翻译":["TranslationUi.kt"],"课堂生词":["VocabularyUi.kt"],"地图":["CampusMapHub.kt","CampusMapUi.kt"],"会议纪要":["MeetingScreens.kt"],"二手信息":["MarketScreen.kt"],"资料库":["LibraryUi.kt"]}
pattern=re.compile(r'surfaceTool\("([^"\n]+)","([^"\n]+)","([^"\n]*)"(?:,(false|true))?\)')
result={}
for module,files in modules.items():
 rows=[]
 for name in files:
  text=(source/name).read_text(encoding='utf-8')
  found=list(pattern.finditer(text))
  if len(found)!=text.count('surfaceTool('):raise SystemExit(f'Unparsed tool in {name}')
  rows.extend(dict(op=m[1],description=m[2],fields=[k for k in m[3].split(',') if k],writes=m[4]!='false') for m in found)
 assert len({r['op'] for r in rows})==len(rows),module
 result[module]=rows
compact=json.dumps(result,ensure_ascii=False,separators=(',',':'))
kotlin='package cn.dapan.assistant\n\nimport org.json.JSONObject\n\n/** Generated by scripts/assistant-catalogue.py; do not edit by hand. */\nobject AssistantCatalogue {\n fun json()=JSONObject(\"\"\"'+compact+'\"\"\")\n}\n'
outputs={root/'assistant-capabilities.json':json.dumps(result,ensure_ascii=False,indent=2)+'\n',source/'AssistantCatalogue.kt':kotlin}
for path,text in outputs.items():
 if '--check' in sys.argv:
  if not path.exists() or path.read_text(encoding='utf-8')!=text:raise SystemExit(f'Catalogue outdated: {path.name}')
 else:path.write_text(text,encoding='utf-8')
print(f'{sum(map(len,result.values()))} operations across {len(result)} modules; catalogue verified')
