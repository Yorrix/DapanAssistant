package cn.dapan.assistant

object ClassroomSpeechStyle {
    data class Level(val name: String, val minChars: Int, val maxChars: Int, val description: String, val guidance: String)
    val levels = listOf(
        Level("一句话", 8, 18, "只说一句最直白的想法，不解释。", "只给一个最容易想到的结论。像基础很弱、没准备的大学生随口说一句；表达单薄，不展开，不给理由，不举例。"),
        Level("简单一说", 19, 30, "一个简单想法，附半句直接理由。", "只说一个简单结论，补半句最直接的理由。用最常见的词，不展开过程，不举例，不补背景。"),
        Level("最直白", 31, 45, "一两句，结论加一个浅显理由。", "用一两句表达一个结论和一个完整但浅显的理由。只抓最容易理解的一点，不补背景，不讨论其他角度。"),
        Level("简单口语", 46, 80, "两三句，说清观点与简单因果。", "像基础一般的大学生，用两三句说清结论和简单因果。说明理由怎样支持结论，句子短，词汇常见，不作多角度分析。"),
        Level("稍有准备", 81, 120, "观点加解释，补一条贴题依据。", "像稍作准备的大学生，表达明确观点，解释主要原因，并补一条直接相关的依据或必要的具体说明。组织连贯，保持口语，不只重复结论。"),
        Level("比较熟练", 121, 160, "论证有条理，解释相关课程概念。", "像表达熟练的大学生，结论、依据和推理衔接清楚。题目需要时解释相关课程概念，结合条件或一个紧扣问题的例子说明，避免只列术语。"),
        Level("完整规范", 161, 210, "完整回应问题，说明依据与适用条件。", "给出较完整、准确的课堂论述，覆盖问题的主要方面，说明依据、推理和必要的适用条件或边界。题目涉及课程概念时准确使用并解释其关系，避免遗漏关键限定；措辞规范但适合口头表达。")
    )
    fun instruction(level: Int): String {
        val style = levels[(level - 1).coerceIn(0, levels.lastIndex)]
        return "表达要求：约${style.minChars}至${style.maxChars}个汉字。${style.guidance}" +
            "上述要求只控制表达难度、篇幅和展开程度，不规定回答的主题、立场或结论。" +
            "使用问题本身所属领域的内容；不能为了符合风格添加无关主题、口号或固定开头。" +
            "简单不等于错误，不故意制造事实错误或语病；问题只需极短事实答案时不为凑字数扩写。"
    }
}
